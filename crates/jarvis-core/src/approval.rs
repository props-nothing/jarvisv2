//! Durable approval requests: a decision record, never a bearer token.
//!
//! `docs/architecture/security.md` describes an approval as "a decision record, not a model message",
//! and `docs/architecture/events-and-workflows.md` adds the constraint that decides the whole design:
//! "Approval is not a permanent bearer token."
//!
//! # Four things this module makes unrepresentable
//!
//! 1. **An approval without a bound intent.** [`CanonicalIntentHash`] is computed from the tool, its
//!    version, and the exact arguments. `security.md`: "Editing the action invalidates the approval."
//!    A hash that a caller could supply would be a hash a caller could supply wrongly, so the
//!    constructor computes it from the parts rather than accepting one.
//! 2. **A nonce that is not a secret.** [`DecisionNonce`] is 32 random bytes generated by the
//!    platform, compared in constant time, and redacted from `Debug`. `security.md` lists "model
//!    self-approval / confused deputy" as a threat whose control is an "authenticated approval
//!    receipt"; a nonce a model could read or guess would be neither.
//! 3. **An approval weaker than the action.** The required [`AuthenticationStrength`] is a field of
//!    the request, and a decision below it is refused by [`ApprovalRequest::apply_decision`] rather
//!    than recorded.
//! 4. **An approval that outlives its intent.** Expiry is checked by [`ApprovalRequest::state_at`],
//!    and the state is derived from the stored decision plus the clock — so a lapsed approval cannot
//!    report itself approved, whatever a caller asks.
//!
//! # Why expiry is compared in Rust and not in SQL
//!
//! `crates/jarvis-core/tests` pins a real defect: [`crate::UtcTimestamp`]'s stored form omits the
//! fractional part when it is zero, so `"...00Z"` sorts **after** `"...00.5Z"` as text. A SQL
//! predicate like `expires_at < now` would therefore treat an expired row as unexpired. Expiry here
//! is compared with [`UtcTimestamp::unix_nanos`], which is the same instant and always comparable.

