    /// Every state's name round-trips, and only `Pending` is decidable.
    #[test]
    fn states_round_trip_and_only_pending_is_decidable() {
        for state in ApprovalState::all() {
            assert_eq!(state.as_str().parse::<ApprovalState>(), Ok(state));
            let encoded = serde_json::to_string(&state).unwrap_or_else(|error| panic!("{error}"));
            assert_eq!(encoded, format!("\"{}\"", state.as_str()));
            assert_eq!(state.is_decidable(), state == ApprovalState::Pending);
            assert_eq!(state.authorizes(), state == ApprovalState::Approved);
        }
    }

    /// Every strength and channel name round-trips, and the ordering is documented.
    #[test]
    fn strengths_and_channels_round_trip() {
        for strength in AuthenticationStrength::all() {
            assert_eq!(
                strength.as_str().parse::<AuthenticationStrength>(),
                Ok(strength)
            );
            let encoded =
                serde_json::to_string(&strength).unwrap_or_else(|error| panic!("{error}"));
            assert_eq!(encoded, format!("\"{}\"", strength.as_str()));
        }
        assert!(AuthenticationStrength::Absent < AuthenticationStrength::Present);
        assert_eq!(AuthenticationStrength::Absent.level(), 0);
        assert_eq!(AuthenticationStrength::Present.level(), 3);

        for channel in ApprovalChannel::all() {
            assert_eq!(channel.as_str().parse::<ApprovalChannel>(), Ok(channel));
        }
        assert!("smoke_signal".parse::<ApprovalChannel>().is_err());
    }

    /// The default expiry is inside the bound the type accepts, from any clock.
    #[test]
    fn the_default_expiry_is_within_the_bound() {
        let clock = At(base());
        let expiry = ApprovalRequest::default_expiry(&clock);
        let created = at(0);
        let lifetime = (expiry.unix_nanos() - created.unix_nanos()) / 1_000_000_000;
        assert_eq!(lifetime, i128::from(MAX_APPROVAL_LIFETIME_SECONDS));
        assert!(expiry > created);
    }
