/// Explains why an approval field was rejected.
#[derive(Clone, Copy, Debug, Eq, Error, PartialEq)]
pub enum InvalidApprovalField {
    /// The preview was empty or oversized.
    #[error("an approval preview must be 1 to {MAX_APPROVAL_PREVIEW_CHARS} characters")]
    Preview,
    /// The expiry was not after the creation time.
    #[error("an approval expiry must be after its creation time")]
    ExpiryNotAfterCreation,
    /// The lifetime exceeded [`MAX_APPROVAL_LIFETIME_SECONDS`].
    #[error("an approval may not live longer than {MAX_APPROVAL_LIFETIME_SECONDS} seconds")]
    LifetimeTooLong,
    /// The requested authentication strength was not a known value.
    #[error("unknown authentication strength")]
    UnknownStrength,
    /// The decision channel was not a known value.
    #[error("unknown approval channel")]
    UnknownChannel,
    /// The actor and approver were the same identity.
    #[error("an approver must not be the actor that requested the action")]
    SelfApproval,
    /// The decision used weaker authentication than the request requires.
    #[error("a decision needs {required} authentication but was supplied {supplied}")]
    InsufficientAuthentication {
        /// The strength the request requires.
        required: AuthenticationStrength,
        /// The strength the decision supplied.
        supplied: AuthenticationStrength,
    },
    /// The presented nonce did not match.
    #[error("the presented decision nonce does not match")]
    NonceMismatch,
    /// The request was loaded from storage, so its nonce is not available to compare.
    ///
    /// A store holds only the nonce's **digest**, so a decoded request cannot verify a presented
    /// nonce and must not pretend to. A caller in this position verifies the nonce against the stored
    /// digest and then calls [`ApprovalRequest::apply_verified_decision`]. This variant is what makes
    /// that requirement enforced rather than documented: without it, the placeholder nonce a decoded
    /// request holds would be a value somebody could present.
    #[error("this approval was loaded from storage; verify the nonce against the stored digest")]
    NonceUnavailable,
    /// A decision was already recorded.
    #[error("this approval has already been decided as {existing}")]
    AlreadyDecided {
        /// The state the approval is already in.
        existing: ApprovalState,
    },
    /// The approval had expired.
    #[error("this approval expired at {expired_at}")]
    Expired {
        /// When it expired.
        expired_at: UtcTimestamp,
    },
}

/// Where an approval is.
///
/// `Expired` is a state rather than a decision, because an approval that lapsed was never decided —
/// recording the lapse as a `Deny` would attribute a decision to a person who made none, and
/// `docs/architecture/runtime-and-models.md` distinguishes the documented `cancelled/expired` edge
/// from a cancellation.
#[derive(Clone, Copy, Debug, Deserialize, Eq, Hash, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ApprovalState {
    /// Waiting for a decision.
    Pending,
    /// Approved, and within its lifetime.
    Approved,
    /// Denied by a person.
    Denied,
    /// Cancelled rather than decided.
    Cancelled,
    /// The lifetime elapsed without a decision.
    Expired,
}

impl ApprovalState {
    /// Returns the stable wire and storage name.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Pending => "pending",
            Self::Approved => "approved",
            Self::Denied => "denied",
            Self::Cancelled => "cancelled",
            Self::Expired => "expired",
        }
    }

    /// Returns whether the approval can still be decided.
    ///
    /// `Approved` is deliberately **not** decidable: an approval is a decision record, so allowing a
    /// second decision would make "the approval" ambiguous and would let a denial be overwritten by a
    /// later approval.
    #[must_use]
    pub const fn is_decidable(self) -> bool {
        matches!(self, Self::Pending)
    }

    /// Returns whether the approval authorized the action.
    ///
    /// Only `Approved`. Every other state — including `Expired` and `Cancelled`, which are not
    /// refusals — must be treated as "not authorized", so a caller checking this cannot mistake a
    /// lapse for permission.
    #[must_use]
    pub const fn authorizes(self) -> bool {
        matches!(self, Self::Approved)
    }

    /// Returns every state.
    #[must_use]
    pub const fn all() -> [Self; 5] {
        [
            Self::Pending,
            Self::Approved,
            Self::Denied,
            Self::Cancelled,
            Self::Expired,
        ]
    }
}

impl fmt::Display for ApprovalState {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

impl FromStr for ApprovalState {
    type Err = InvalidApprovalField;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        match value {
            "pending" => Ok(Self::Pending),
            "approved" => Ok(Self::Approved),
            "denied" => Ok(Self::Denied),
            "cancelled" => Ok(Self::Cancelled),
            "expired" => Ok(Self::Expired),
            _ => Err(InvalidApprovalField::UnknownChannel),
        }
    }
}

/// One decision to record against an approval.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ApprovalDecision {
    outcome: ApprovalDecisionOutcome,
    channel: ApprovalChannel,
    strength: AuthenticationStrength,
    decided_at: UtcTimestamp,
}

/// Which way a decision went.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum ApprovalDecisionOutcome {
    /// The action may proceed, within the lifetime.
    Approve,
    /// The action must not proceed.
    Deny,
    /// The request was withdrawn.
    Cancel,
}

impl ApprovalDecisionOutcome {
    /// Returns the state a decision produces.
    #[must_use]
    pub const fn state(self) -> ApprovalState {
        match self {
            Self::Approve => ApprovalState::Approved,
            Self::Deny => ApprovalState::Denied,
            Self::Cancel => ApprovalState::Cancelled,
        }
    }

    /// Returns the stable storage name.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Approve => "approve",
            Self::Deny => "deny",
            Self::Cancel => "cancel",
        }
    }
}

impl ApprovalDecision {
    /// Declares a decision.
    #[must_use]
    pub const fn new(
        outcome: ApprovalDecisionOutcome,
        channel: ApprovalChannel,
        strength: AuthenticationStrength,
        decided_at: UtcTimestamp,
    ) -> Self {
        Self {
            outcome,
            channel,
            strength,
            decided_at,
        }
    }

    /// Returns which way the decision went.
    #[must_use]
    pub const fn outcome(&self) -> ApprovalDecisionOutcome {
        self.outcome
    }

    /// Returns the channel that answered.
    #[must_use]
    pub const fn channel(&self) -> ApprovalChannel {
        self.channel
    }

    /// Returns the strength behind the decision.
    #[must_use]
    pub const fn strength(&self) -> AuthenticationStrength {
        self.strength
    }

    /// Returns when the decision was made.
    #[must_use]
    pub const fn decided_at(&self) -> UtcTimestamp {
        self.decided_at
    }
}

/// One durable approval request.
///
/// Immutable after construction except through [`Self::apply_decision`], which is the only door and
/// enforces the four rules in the module comment.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ApprovalRequest {
    id: ApprovalId,
    workspace_id: WorkspaceId,
    run_id: RunId,
    actor_id: String,
    tool: String,
    tool_version: String,
    intent: CanonicalIntentHash,
    preview: SafeMessage,
    risk_level: u8,
    required_strength: AuthenticationStrength,
    nonce: DecisionNonce,
    correlation_id: CorrelationId,
    created_at: UtcTimestamp,
    expires_at: UtcTimestamp,
    decision: Option<ApprovalDecision>,
    /// Whether this value holds the real nonce. `false` for a record rebuilt from storage, which
    /// holds only the digest — see [`InvalidApprovalField::NonceUnavailable`].
    nonce_usable: bool,
}

/// The declared fields of an approval request.
///
/// A struct rather than ten positional parameters, and without `Default`, so every field is stated
