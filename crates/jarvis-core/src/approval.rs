/// Maximum characters in a human-readable approval preview.
///
/// Bounded because the preview reaches a person on an approval prompt and a client on every channel.
/// It is a *preview*: the canonical intent hash is what the decision binds to, so shortening the
/// preview cannot change what was approved.
pub const MAX_APPROVAL_PREVIEW_CHARS: usize = 512;

/// Maximum characters in a canonicalized intent string.
///
/// Bounded before hashing, so an enormous argument object cannot make the hash computation itself a
/// denial-of-service, and so the limit is the same for the value that is stored and hashed.
pub const MAX_CANONICAL_INTENT_CHARS: usize = 8192;

/// Maximum approval lifetime in seconds.
///
/// Bounded because an approval that outlives its intent is the failure mode the expiry exists to
/// prevent, and `docs/architecture/events-and-workflows.md` requires an expiry on every approval. An
/// hour is long enough for a person to answer a prompt and short enough that a stored grant cannot
/// survive an incident response.
pub const MAX_APPROVAL_LIFETIME_SECONDS: u32 = 3600;

/// Explains why a canonical intent could not be hashed.
#[derive(Clone, Copy, Debug, Eq, Error, PartialEq)]
pub enum IntentError {
    /// The canonicalized text was empty.
    #[error("a canonical intent must not be empty")]
    Empty,
    /// The canonicalized text exceeded the bound.
    #[error("a canonical intent exceeds {MAX_CANONICAL_INTENT_CHARS} characters")]
    TooLong,
    /// The arguments were not a JSON object.
    ///
    /// A tool's input schema is an object, so arguments that are not an object did not come from a
    /// validated call and cannot be canonicalized deterministically.
    #[error("tool arguments must be a JSON object")]
    ArgumentsNotAnObject,
    /// The arguments could not be canonicalized.
    #[error("tool arguments could not be canonicalized")]
    NotCanonicalizable,
}

/// A digest of exactly the intent a decision approves.
///
/// The value is a lowercase hexadecimal SHA-256 digest. It is stored and compared, so the
/// representation is the digest itself rather than a wrapper enum that could hold a value it did not
/// compute.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct CanonicalIntentHash([u8; 32]);

impl CanonicalIntentHash {
    /// Computes the hash of a tool call's intent.
    ///
    /// # Errors
    ///
    /// Returns [`IntentError::ArgumentsNotAnObject`] when `arguments` is not an object,
    /// [`IntentError::NotCanonicalizable`] when it cannot be serialized,
    /// [`IntentError::Empty`] when no part is usable, and [`IntentError::TooLong`] when the
    /// canonicalized text exceeds [`MAX_CANONICAL_INTENT_CHARS`].
    ///
    /// # Why the parts are hashed with separators
    ///
    /// The canonical text joins tool, version, and canonicalized arguments with a character that
    /// cannot appear in an identifier (`\u{1f}`). Without a separator, a tool named `a` with version
    /// `bc` and a tool named `ab` with version `c` would produce the same digest, so one approval
    /// would authorize the other.
    pub fn compute(
        tool: &str,
        tool_version: &str,
        arguments: &serde_json::Value,
    ) -> Result<Self, IntentError> {
        use sha2::{Digest, Sha256};

        if !arguments.is_object() {
            return Err(IntentError::ArgumentsNotAnObject);
        }
        let canonical_arguments = canonicalize(arguments)?;
        let canonical = format!("{tool}\u{1f}{tool_version}\u{1f}{canonical_arguments}");
        if canonical.trim().is_empty() {
            return Err(IntentError::Empty);
        }
        if canonical.chars().count() > MAX_CANONICAL_INTENT_CHARS {
            return Err(IntentError::TooLong);
        }

        let mut hasher = Sha256::new();
        hasher.update(canonical.as_bytes());
        let digest = hasher.finalize();
        let mut bytes = [0u8; 32];
        bytes.copy_from_slice(&digest);
        Ok(Self(bytes))
    }

    /// Returns the digest as lowercase hexadecimal.
    #[must_use]
    pub fn to_hex(self) -> String {
        encode_hex(&self.0)
    }
}

impl fmt::Display for CanonicalIntentHash {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.to_hex())
    }
}

impl FromStr for CanonicalIntentHash {
    type Err = IntentError;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        // A digest is 32 bytes, so the hex text is exactly 64 characters. Anything else did not
        // come from `compute`, so it is refused rather than padded or truncated.
        if value.len() != 64 || !value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
            return Err(IntentError::NotCanonicalizable);
        }
        let mut bytes = [0u8; 32];
        for (index, chunk) in value.as_bytes().as_chunks::<2>().0.iter().enumerate() {
            let text = std::str::from_utf8(chunk).map_err(|_| IntentError::NotCanonicalizable)?;
            bytes[index] =
                u8::from_str_radix(text, 16).map_err(|_| IntentError::NotCanonicalizable)?;
        }
        Ok(Self(bytes))
    }
}

impl Serialize for CanonicalIntentHash {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        serializer.serialize_str(&self.to_hex())
    }
}

impl<'de> Deserialize<'de> for CanonicalIntentHash {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let value = String::deserialize(deserializer)?;
        value.parse().map_err(serde::de::Error::custom)
    }
}

/// Renders JSON with object keys in a deterministic order.
///
/// `serde_json::Map` is a `BTreeMap` unless the `preserve_order` feature is enabled, so its default
/// serialization is already sorted — but that is a property of a feature flag rather than of this
/// code, and a feature added for an unrelated reason would silently make two equal argument objects
/// hash differently. Sorting explicitly here makes the canonical form independent of that choice.
fn canonicalize(value: &serde_json::Value) -> Result<String, IntentError> {
    /// Rebuilds a value with object keys in ascending order.
    fn sorted(value: &serde_json::Value) -> serde_json::Value {
        match value {
            serde_json::Value::Object(object) => {
                let mut ordered = serde_json::Map::new();
                let mut keys: Vec<&String> = object.keys().collect();
                keys.sort();
                for key in keys {
                    if let Some(entry) = object.get(key) {
                        ordered.insert(key.clone(), sorted(entry));
                    }
                }
                serde_json::Value::Object(ordered)
            }
            serde_json::Value::Array(items) => {
                serde_json::Value::Array(items.iter().map(sorted).collect())
            }
            other => other.clone(),
        }
    }
    serde_json::to_string(&sorted(value)).map_err(|_| IntentError::NotCanonicalizable)
}

/// Explains why a decision nonce was rejected.
#[derive(Clone, Copy, Debug, Eq, Error, PartialEq)]
pub enum NonceError {
    /// The text was not the fixed encoded length.
    #[error("a decision nonce must be exactly {CREDENTIAL_CHARS} hexadecimal characters")]
    Length,
    /// The text contained a non-hexadecimal character.
    #[error("a decision nonce contains a non-hexadecimal character")]
    NotHexadecimal,
    /// The platform random source was unavailable.
    #[error("random bytes are unavailable")]
    RandomUnavailable,
}

/// The one-time secret an approval decision must present.
///
/// Generated by the platform, never by the model. `docs/architecture/security.md` lists a one-time
/// decision nonce as part of the record whose purpose is to defeat "model self-approval / confused
/// deputy", so a nonce the requesting model could read or choose would defeat the control it exists
/// for.
///
/// The value is zeroized on drop and redacted from `Debug`, because a nonce that reaches a log line
/// is a nonce that has leaked.
#[derive(Clone, Eq)]
pub struct DecisionNonce {
    encoded: Vec<u8>,
}

impl DecisionNonce {
    /// Generates a nonce from the platform random source.
    ///
    /// # Errors
    ///
    /// Returns [`NonceError::RandomUnavailable`] when the platform source fails. The failure is
    /// propagated rather than retried or replaced with a weaker source: an approval whose nonce was
    /// guessable is worse than an approval that could not be created.
    pub fn generate() -> Result<Self, NonceError> {
        let mut bytes = [0u8; CREDENTIAL_BYTES];
        getrandom::fill(&mut bytes).map_err(|_| NonceError::RandomUnavailable)?;
        Ok(Self {
            encoded: encode_hex(&bytes).into_bytes(),
        })
    }

    /// Parses a nonce from hexadecimal text, normalizing case and trimming.
    ///
    /// # Errors
    ///
    /// Returns [`NonceError::Length`] when the text is not the fixed encoded length, or
    /// [`NonceError::NotHexadecimal`] when it contains a non-hexadecimal character.
    pub fn parse(text: &str) -> Result<Self, NonceError> {
        let trimmed = text.trim();
        if trimmed.len() != CREDENTIAL_CHARS {
            return Err(NonceError::Length);
        }
        if !trimmed.bytes().all(|byte| byte.is_ascii_hexdigit()) {
            return Err(NonceError::NotHexadecimal);
        }
        Ok(Self {
            encoded: trimmed.to_ascii_lowercase().into_bytes(),
        })
    }

    /// Returns the encoded nonce for storage.
    ///
    /// Named `expose` to make each call a deliberate act, matching how the client credential is read.
    #[must_use]
    pub fn expose(&self) -> &str {
        // The buffer only ever holds validated ASCII hexadecimal bytes.
        str::from_utf8(&self.encoded).unwrap_or_default()
    }

    /// Compares a presented nonce in constant time.
    #[must_use]
    pub fn matches(&self, presented: &str) -> bool {
        constant_time_eq(&self.encoded, presented.as_bytes())
    }
}

impl PartialEq for DecisionNonce {
    /// Compares in constant time, so equality does not leak a prefix.
    fn eq(&self, other: &Self) -> bool {
        constant_time_eq(&self.encoded, &other.encoded)
    }
}

impl fmt::Debug for DecisionNonce {
    /// Redacts the value, so a nonce cannot reach a log or a panic message.
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("DecisionNonce([REDACTED])")
    }
}

impl fmt::Display for DecisionNonce {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("approval decision nonce [REDACTED]")
    }
}

impl Drop for DecisionNonce {
    fn drop(&mut self) {
        self.encoded.fill(0);
    }
}

/// How strong the authentication behind a decision was.
///
/// Deliberately distinct from `jarvis-tools`'s channel ceiling. The ceiling is what a channel *can*
/// establish; this is what the channel that answered *did* establish. Sharing one type would let a
/// caller record a ceiling as if it were an observation.
#[derive(Clone, Copy, Debug, Deserialize, Eq, Hash, Ord, PartialEq, PartialOrd, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum AuthenticationStrength {
    /// No authentication evidence.
    Absent,
    /// Channel evidence only, such as a caller ID.
    ChannelEvidence,
    /// A verified credential, such as a device credential.
    Credential,
    /// A credential established in this interaction, with user presence.
    Present,
}

impl AuthenticationStrength {
    /// Returns the stable wire and storage name.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Absent => "absent",
            Self::ChannelEvidence => "channel_evidence",
            Self::Credential => "credential",
            Self::Present => "present",
        }
    }

    /// Returns the numeric level, for comparison against a stored value.
    #[must_use]
    pub const fn level(self) -> u8 {
        match self {
            Self::Absent => 0,
            Self::ChannelEvidence => 1,
            Self::Credential => 2,
            Self::Present => 3,
        }
    }

    /// Returns every strength, from weakest to strongest.
    #[must_use]
    pub const fn all() -> [Self; 4] {
        [
            Self::Absent,
            Self::ChannelEvidence,
            Self::Credential,
            Self::Present,
        ]
    }
}

impl fmt::Display for AuthenticationStrength {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

impl FromStr for AuthenticationStrength {
    type Err = InvalidApprovalField;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        match value {
            "absent" => Ok(Self::Absent),
            "channel_evidence" => Ok(Self::ChannelEvidence),
            "credential" => Ok(Self::Credential),
            "present" => Ok(Self::Present),
            _ => Err(InvalidApprovalField::UnknownStrength),
        }
    }
}

